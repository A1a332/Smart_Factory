#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the 56 MAM research-schematic classes for the Remote_Factory upgrade tree.

结构（2026-10-07 用户定案，结构图见 F:/Workbuddy/SMLDev/WT_MAM_研究树结构图.svg）：
    3 个功能轨 x 4 个阶段 x 4 级 = 48  （Lv1 ~ Lv16，命名 UWTUpg_{Cap|Sto|Shd}_S{阶段}_L{全局级}）
  + 末段 2 条路线 x 4 级         =  8  （Lv17 ~ Lv20，命名 UWTUpg_Final{Plain|Boost}_L{级}）
  = 56 个 schematic

MAM 树里只放 14 个方块（3 列 x 4 层 = 12 + 末段 2），每个方块内 4 级共用同一个坐标，
靠 NodesToUnhide 逐级揭示 —— 见 Remote_FactoryResearchTree.cpp。

Outputs（不要把生成区当手写代码，改完跑本脚本重新生成）：
  - Remote_FactoryUpgradeResearch.h  -> 56 个 UCLASS 声明，注入 AUTO-GEN 标记区
    （必须留在主头文件、且位于 ".generated.h" 之前，UHT 才会认）
  - Remote_FactoryUpgradeResearch.gen.cpp -> 56 个空构造函数 + 定义表 + 三个查询函数
"""
import os
import re

# (枚举 token, 类名前缀, 显示用中文轨名)
TRACKS = [
    ("Storage",      "Cap"),   # 大容量仓库
    ("PowerStorage", "Sto"),   # 储能单元
    ("Accelerator",  "Shd"),   # 强化能量碎片
]
STAGES = 4
PER_STAGE = 4
FINAL_LEVELS = [17, 18, 19, 20]
ROUTES = [("Plain", 1), ("Boost", 2)]   # (名字, EWTFinalRoute 数值)

HERE = os.path.dirname(os.path.abspath(__file__))
H = os.path.join(HERE, "Remote_FactoryUpgradeResearch.h")
CPP = os.path.join(HERE, "Remote_FactoryUpgradeResearch.gen.cpp")
OLD_GEN_H = os.path.join(HERE, "Remote_FactoryUpgradeResearch.gen.h")


def stage_of(level):
    return (level - 1) // PER_STAGE + 1


# ---- 收集 56 个类的 (类名, 轨token, 全局级, route) ------------------------------
defs = []
for tenum, abbr in TRACKS:
    for L in range(1, STAGES * PER_STAGE + 1):
        defs.append(("UWTUpg_%s_S%d_L%02d" % (abbr, stage_of(L), L), tenum, L, 0))
for rname, rval in ROUTES:
    for L in FINAL_LEVELS:
        defs.append(("UWTUpg_Final%s_L%02d" % (rname, L), "Storage", L, rval))

assert len(defs) == 56, len(defs)
assert len(set(d[0] for d in defs)) == 56

# ---- 头文件：56 个 UCLASS 声明（UHT 不展开宏，必须逐个显式写出） -----------------
class_lines = []
for cls, _t, _l, _r in defs:
    class_lines.append("UCLASS()")
    class_lines.append("class REMOTEFACTORY_API %s : public UWTUpgradeResearchBase" % cls)
    class_lines.append("{")
    class_lines.append("    GENERATED_BODY()")
    class_lines.append("public:")
    class_lines.append("    %s();" % cls)
    class_lines.append("};")

MARKER = re.compile(
    r"// >>> AUTO-GEN WT RESEARCH CLASSES START >>>.*?// <<< AUTO-GEN WT RESEARCH CLASSES END <<<",
    re.S,
)
header = open(H, "r", encoding="utf-8").read()
block = (
    "// >>> AUTO-GEN WT RESEARCH CLASSES START >>>\n"
    + "\n".join(class_lines)
    + "\n// <<< AUTO-GEN WT RESEARCH CLASSES END <<<"
)
new_header, n = MARKER.subn(block, header)
if n != 1:
    raise SystemExit("marker region not found/replaced exactly once in header (n=%d)" % n)
# ★0.2.139：两个产物的行尾基线不同（.h 是 LF、.gen.cpp 是 CRLF），而 Python 文本写默认会把 \n
#   转成系统 os.linesep(Windows=\r\n)，跑一次脚本就会把 .h 的整份行尾改掉（表现为全文件 diff）。
#   显式指定 newline，保证「跑脚本后产物逐字节可重现」（自检 _selfcheck_0139.py 深检④ 守着这点）。
open(H, "w", encoding="utf-8", newline="\n").write(new_header)

# ---- .gen.cpp -----------------------------------------------------------------
c = []
c.append("// GENERATED by gen_wt_research.py -- DO NOT EDIT BY HAND")
c.append("// 56 = 3 轨 x 4 阶段 x 4 级 + 末段 2 路线 x 4 级")
c.append('#include "Remote_FactoryUpgradeResearch.h"')
c.append('// ★0.2.138：末段·碎片路线（Boost）节点随 WT_FEATURE_POWER_SHARD 闸门一起下架 —— 闸门常量在 Registry.h。')
c.append('// ★0.2.139：MAM 研究总闸 WT_FEATURE_MAM_RESEARCH（v1.0.0 前 56 条全部下架）—— 同上，常量在 Registry.h。')
c.append('#include "Remote_FactoryRegistry.h"')
c.append("")
for cls, tenum, L, _r in defs:
    # ★ 构造函数必须保持空：Apply() 会 StaticLoadClass + NewObject，在 UObject 构造期非法。
    #   真正的数据由 WT_ConfigureAllResearch() 在 GWM CONSTRUCTION 阶段按 CDO 逐个写入。
    c.append("WT_RIMPL(%s, %s, %d)" % (cls, tenum, L))
c.append("")

# 定义表：类 -> (轨, 全局级, 路线)
c.append("struct FWTResearchDef")
c.append("{")
c.append("    TSubclassOf<UWTUpgradeResearchBase> Class;")
c.append("    EWTUpgradeTrack Track;")
c.append("    int32 Level;          // 1 ~ 20")
c.append("    EWTFinalRoute Route;  // Lv1~16 恒为 None；Lv17~20 为 Plain / Boost")
c.append("};")
c.append("")
c.append("static const FWTResearchDef GWTResearchDefs[] = {")
for cls, tenum, L, rval in defs:
    rtxt = "EWTFinalRoute::None" if rval == 0 else ("EWTFinalRoute::Plain" if rval == 1 else "EWTFinalRoute::Boost")
    c.append("    { %s::StaticClass(), EWTUpgradeTrack::%s, %d, %s }," % (cls, tenum, L, rtxt))
c.append("};")
c.append("static const int32 GWTResearchDefCount = UE_ARRAY_COUNT(GWTResearchDefs);")
c.append("")

# 配置入口
c.append("void WT_ConfigureAllResearch()")
c.append("{")
c.append("    // ★0.2.139 闸门（WT_FEATURE_MAM_RESEARCH，用户定案「v1.0.0 前 MAM 科技全部下架」）：")
c.append("    //   关=不配这 60 个研究 CDO（省掉启动期资产加载 + 每局 56 条 reward 警告）。")
c.append("    //   v1.0.0 把 Remote_FactoryRegistry.h 的 WT_FEATURE_MAM_RESEARCH 翻回 true 即恢复。")
c.append("    if (!WT_FEATURE_MAM_RESEARCH) return;")
c.append("    static bool bConfigured = false;")
c.append("    if (bConfigured) return;")
c.append("    for (int32 i = 0; i < GWTResearchDefCount; ++i)")
c.append("    {")
c.append("        const FWTResearchDef& D = GWTResearchDefs[i];")
c.append("        if (!D.Class) continue;")
c.append("        if (UWTUpgradeResearchBase* CDO = Cast<UWTUpgradeResearchBase>(D.Class->GetDefaultObject()))")
c.append("        {")
c.append("            CDO->Apply(D.Track, D.Level, D.Route);")
c.append("        }")
c.append("    }")
c.append("    bConfigured = true;")
c.append('    WT_LOGF(TEXT("[research] configured %d upgrade research schematics (CDO)."), GWTResearchDefCount);')
c.append("}")
c.append("")

# WT_ResearchClassFor(Track, Level)  —— 只覆盖 Lv1~16（Lv17~20 是路线相关，用下面那个）
c.append("TSubclassOf<UFGSchematic> WT_ResearchClassFor(EWTUpgradeTrack Track, int32 Level)")
c.append("{")
c.append("    if (Level < 1 || Level > WT_Stage4MaxLevel) return nullptr;")
for tenum, abbr in TRACKS:
    c.append("    if (Track == EWTUpgradeTrack::%s) {" % tenum)
    c.append("        switch (Level) {")
    for L in range(1, STAGES * PER_STAGE + 1):
        c.append("            case %d: return UWTUpg_%s_S%d_L%02d::StaticClass();" % (L, abbr, stage_of(L), L))
    c.append("        }")
    c.append("    }")
c.append("    return nullptr;")
c.append("}")
c.append("")

# WT_FinalResearchClassFor(Route, Level) —— 末段两条路线
c.append("TSubclassOf<UFGSchematic> WT_FinalResearchClassFor(EWTFinalRoute Route, int32 Level)")
c.append("{")
c.append("    if (Level < WT_FinalMinLevel || Level > WT_MaxUpgradeLevel) return nullptr;")
for rname, rval in ROUTES:
    c.append("    if (Route == EWTFinalRoute::%s) {" % rname)
    c.append("        switch (Level) {")
    for L in FINAL_LEVELS:
        c.append("            case %d: return UWTUpg_Final%s_L%02d::StaticClass();" % (L, rname, L))
    c.append("        }")
    c.append("    }")
c.append("    return nullptr;")
c.append("}")
c.append("")

# WT_GetAllUpgradeResearch()
c.append("TArray<TSubclassOf<UFGSchematic>> WT_GetAllUpgradeResearch()")
c.append("{")
c.append("    TArray<TSubclassOf<UFGSchematic>> Out;")
c.append("    // ★0.2.139 闸门（WT_FEATURE_MAM_RESEARCH，用户定案「v1.0.0 前 MAM 科技全部下架」）：")
c.append("    //   关=60 条 EST_MAM 节点一条都不注册（进不了 mSchematics ⇒ SML 不 RegisterSchematic）。")
c.append("    //   升级建筑 0.2.56 已整条移除，这些节点当前既不可见也无作用，下架零副作用。")
c.append("    //   v1.0.0 翻 true 恢复；注意还需让 WT_GetAllResearchTrees() 返回树，MAM 里才看得见。")
c.append("    if (!WT_FEATURE_MAM_RESEARCH) return Out;")
c.append("    Out.Reserve(GWTResearchDefCount);")
c.append("    for (int32 i = 0; i < GWTResearchDefCount; ++i)")
c.append("    {")
c.append("        // ★0.2.138 闸门（WT_FEATURE_POWER_SHARD，用户定案「一并下架」）：")
c.append("        //   末段·碎片路线（Boost）节点的造价含强化能量碎片（见 Apply() 里的 mCost.Add），")
c.append("        //   碎片下架期间这些节点「看得见、做不了」⇒ 随碎片一起下架。")
c.append("        //   v1.0.0 把 Remote_FactoryRegistry.h 的闸门翻回 true 即自动回来（与碎片同一开关）。")
c.append("        if (!WT_FEATURE_POWER_SHARD && GWTResearchDefs[i].Route == EWTFinalRoute::Boost)")
c.append("        {")
c.append("            continue;")
c.append("        }")
c.append("        Out.Add(GWTResearchDefs[i].Class);")
c.append("    }")
c.append("    return Out;")
c.append("}")
open(CPP, "w", encoding="utf-8", newline="\r\n").write("\n".join(c))

if os.path.exists(OLD_GEN_H):
    os.remove(OLD_GEN_H)

print("gen_wt_research.py: %d classes (%d track + %d final) injected into header + .gen.cpp"
      % (len(defs), 3 * STAGES * PER_STAGE, 2 * len(FINAL_LEVELS)))
